import random

DEFAULT_SETS = [
    ["Да", "Нет", "Не знаю"],
    ["Приду", "Не приду", "Пока не знаю"],
    ["Буду", "Не буду", "Не уверен"],
    ["Иду", "Не иду", "Пока не решил"],
    ["Буду на месте", "Не смогу", "Под вопросом"],
    ["Да, буду", "Не получится", "Пока не ясно"],
]


def pick_default_answers() -> list[str]:
    return list(random.choice(DEFAULT_SETS))
